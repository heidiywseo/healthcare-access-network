"""Optional: create real Census tract outlines for the map from a Census cartographic boundary shapefile.
Usage: python prepare_tract_boundaries.py /path/to/cb_2024_42_tract_500k.shp
Download the Pennsylvania tract file (cb_<year>_42_tract_500k.zip) from
https://www.census.gov/geographies/mapping-files/time-series/geo/cartographic-boundary.html and unzip it.
The .shp and .dbf files must sit side by side. No extra libraries or network access needed.
Writes assets/tract_boundaries.js, which the map uses to draw tract polygons.
"""
import json, struct, sys
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parent
TOLERANCE = 0.00005  # degrees (~5 m); Douglas-Peucker simplification to keep the file small


def read_dbf(path):
    data = path.read_bytes()
    nrec, hlen, rlen = struct.unpack('<IHH', data[4:12])
    fields, pos = [], 32
    while data[pos] != 0x0D:
        name = data[pos:pos + 11].split(b'\0')[0].decode('ascii')
        fields.append((name, data[pos + 16]))
        pos += 32
    rows = []
    for i in range(nrec):
        off = hlen + i * rlen + 1  # skip deletion flag
        row = {}
        for name, size in fields:
            row[name] = data[off:off + size].decode('latin-1').strip()
            off += size
        rows.append(row)
    return rows


def read_polygons(path):
    data = path.read_bytes()
    pos, shapes = 100, []
    while pos < len(data):
        _, words = struct.unpack('>ii', data[pos:pos + 8])
        content = data[pos + 8:pos + 8 + words * 2]
        pos += 8 + words * 2
        stype = struct.unpack('<i', content[:4])[0]
        if stype == 0:
            shapes.append([])
            continue
        if stype not in (5, 15, 25):
            raise SystemExit(f'Unexpected shape type {stype}; expected polygons')
        nparts, npts = struct.unpack('<ii', content[36:44])
        parts = list(struct.unpack(f'<{nparts}i', content[44:44 + 4 * nparts])) + [npts]
        base = 44 + 4 * nparts
        pts = struct.unpack(f'<{2 * npts}d', content[base:base + 16 * npts])
        shapes.append([[(pts[2 * k], pts[2 * k + 1]) for k in range(parts[j], parts[j + 1])] for j in range(nparts)])
    return shapes


def simplify(ring, tol):
    if len(ring) < 5:
        return ring
    keep = [False] * len(ring)
    keep[0] = keep[-1] = True
    stack = [(0, len(ring) - 1)]
    while stack:
        a, b = stack.pop()
        (x1, y1), (x2, y2) = ring[a], ring[b]
        dx, dy = x2 - x1, y2 - y1
        norm = (dx * dx + dy * dy) ** 0.5
        best, idx = -1.0, None
        for k in range(a + 1, b):
            x, y = ring[k]
            d = abs(dy * (x - x1) - dx * (y - y1)) / norm if norm else ((x - x1) ** 2 + (y - y1) ** 2) ** 0.5
            if d > best:
                best, idx = d, k
        if idx is not None and best > tol:
            keep[idx] = True
            stack += [(a, idx), (idx, b)]
    out = [p for p, k in zip(ring, keep) if k]
    return out if len(out) >= 4 else ring


if len(sys.argv) != 2:
    raise SystemExit('Usage: python prepare_tract_boundaries.py /path/to/cb_<year>_42_tract_500k.shp')
shp = Path(sys.argv[1])
dbf = shp.with_suffix('.dbf')
if not dbf.exists():
    raise SystemExit(f'Missing {dbf.name} next to the .shp file')
records, shapes = read_dbf(dbf), read_polygons(shp)
if len(records) != len(shapes):
    raise SystemExit('Shapefile and DBF record counts differ')
if 'GEOID' not in records[0]:
    raise SystemExit('No GEOID field. File must be a Census tract boundary file.')

needed = set(pd.read_csv(ROOT / 'data' / 'synthetic_cohorts.csv', usecols=['tract_geoid'], dtype=str).tract_geoid)
out = {}
for rec, rings in zip(records, shapes):
    geoid = rec['GEOID'].zfill(11)
    if geoid in needed and rings:
        out[geoid] = [[[round(x, 5), round(y, 5)] for x, y in simplify(r, TOLERANCE)] for r in rings]
missing = needed - set(out)
if missing:
    raise SystemExit(f'Not all cohort tracts matched: {len(out)}/{len(needed)}; sample missing: {sorted(missing)[:6]}')
for geoid, rings in out.items():
    for r in rings:
        for x, y in r:
            if not (39.8 <= y <= 40.2 and -75.4 <= x <= -74.9):
                raise SystemExit(f'Tract {geoid} has coordinates outside Philadelphia vicinity')

js = ('// Census tract outlines [lon, lat] rings, generated by prepare_tract_boundaries.py from '
      + shp.name + '. Do not edit by hand.\nwindow.TRACT_SHAPES='
      + json.dumps(out, separators=(',', ':')) + ';\n')
(ROOT / 'assets' / 'tract_boundaries.js').write_text(js, encoding='utf-8')
print(f'Wrote outlines for {len(out)} tracts ({len(js) // 1024} KB). Source file: {shp.name}')
